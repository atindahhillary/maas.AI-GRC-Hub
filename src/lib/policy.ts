import type { OrgProfile, PolicyClause, PolicyTemplate } from './content/types'

const SECTOR_LABEL: Record<OrgProfile['sector'], string> = {
  finance: 'financial services', health: 'healthcare', education: 'education', ngo: 'non-profit',
  government: 'public sector', retail: 'retail', tech: 'technology', logistics: 'logistics', other: 'general business',
}

const COUNTRY: Record<string, string> = { KE: 'Kenya', UG: 'Uganda', TZ: 'Tanzania', RW: 'Rwanda', NG: 'Nigeria', ZA: 'South Africa', GH: 'Ghana', GB: 'United Kingdom', US: 'United States', EU: 'European Union' }

const DATA_LABEL: Record<string, string> = { personal: 'personal data', health: 'health records', financial: 'financial records', children: "children's data", ip: 'intellectual property' }

export const COUNTRY_OPTIONS = Object.entries(COUNTRY)

export function regulators(p: OrgProfile): string[] {
  const out: string[] = []
  const has = (c: string) => p.countries.includes(c)
  if (has('KE')) out.push('Office of the Data Protection Commissioner (Kenya)')
  if (has('KE') && p.sector === 'finance') out.push('Central Bank of Kenya')
  if (has('UG')) out.push('Personal Data Protection Office (Uganda)')
  if (has('TZ')) out.push('Personal Data Protection Commission (Tanzania)')
  if (has('RW')) out.push('National Cyber Security Authority (Rwanda)')
  if (has('NG')) out.push('Nigeria Data Protection Commission')
  if (has('ZA')) out.push('Information Regulator (South Africa)')
  if (has('GH')) out.push('Data Protection Commission (Ghana)')
  if (has('GB')) out.push("Information Commissioner's Office (UK)")
  if (has('EU')) out.push('EU data protection supervisory authorities')
  return out.length ? out : ['your national data protection authority']
}

const list = (items: string[]) => (items.length < 2 ? items.join('') : `${items.slice(0, -1).join(', ')} and ${items.at(-1)}`)

export function tokens(org: string, p: OrgProfile): Record<string, string> {
  return {
    '{org}': org,
    '{sector}': SECTOR_LABEL[p.sector],
    '{regulators}': list(regulators(p)),
    '{countries}': list(p.countries.map((c) => COUNTRY[c] ?? c)) || 'the countries where it operates',
    '{dataTypes}': list(p.dataTypes.map((d) => DATA_LABEL[d])) || 'business data',
    '{securityOwner}': p.hasSecurityLead ? 'Security Lead' : p.size === '1-10' || p.size === '11-50' ? 'Managing Director' : 'IT Lead',
  }
}

const fill = (text: string, t: Record<string, string>) => text.replace(/\{[a-zA-Z]+\}/g, (m) => t[m] ?? m)

export interface PolicyDoc {
  title: string
  summary: string
  kind: PolicyTemplate['kind']
  reviewMonths: number
  purpose: string
  scope: string
  sections: { heading: string; body?: string; clauses: PolicyClause[] }[]
}

export function renderPolicy(tpl: PolicyTemplate, org: string, profile: OrgProfile): PolicyDoc {
  const t = tokens(org, profile)
  return {
    title: tpl.title, summary: fill(tpl.summary, t), kind: tpl.kind, reviewMonths: tpl.reviewMonths,
    purpose: fill(tpl.purpose, t), scope: fill(tpl.scope, t),
    sections: tpl.sections
      .filter((s) => !s.appliesIf || s.appliesIf(profile))
      .map((s) => ({
        heading: fill(s.heading, t),
        body: s.body && fill(s.body, t),
        clauses: s.clauses.map((c) => ({
          ...c, statement: fill(c.statement, t), metric: fill(c.metric, t), target: fill(c.target, t),
          ownerRole: fill(c.ownerRole, t), relevance: fill(c.relevance, t),
        })),
      })),
  }
}

export function policyToMarkdown(doc: PolicyDoc, meta: { org: string; version: number; status: string; approvedBy?: string | null; approvedAt?: string | null }) {
  const lines = [
    `# ${doc.title}`, '',
    `${meta.org} | Version ${meta.version} | ${meta.status}${meta.approvedBy ? ` | Approved by ${meta.approvedBy} on ${meta.approvedAt?.slice(0, 10)}` : ''}`, '',
    `## Purpose`, '', doc.purpose, '', `## Scope`, '', doc.scope, '',
  ]
  doc.sections.forEach((s) => {
    lines.push(`## ${s.heading}`, '')
    if (s.body) lines.push(s.body, '')
    s.clauses.forEach((c, i) => {
      lines.push(`${i + 1}. **${c.statement}**`, `   - Measure: ${c.metric}`, `   - Target: ${c.target}`, `   - Owner: ${c.ownerRole}`, `   - Why: ${c.relevance}`, `   - In place within: ${c.dueDays} days of approval`, '')
    })
  })
  lines.push(`Review this policy every ${doc.reviewMonths} months. Draft generated by maas.AI GRC Hub for human review, not legal advice.`)
  return lines.join('\n')
}
