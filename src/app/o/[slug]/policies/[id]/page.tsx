import { notFound } from 'next/navigation'
import { ArrowLeft } from 'lucide-react'
import Link from 'next/link'
import { PrintButton, SaveMarkdown } from '@/components/doc-tools'
import { day, shortHash } from '@/components/ui'
import { atLeast } from '@/lib/access'
import { loadState } from '@/lib/load'
import { policyToMarkdown, type PolicyDoc } from '@/lib/policy'
import { ApproveButton } from '../generate'

export const metadata = { title: 'Policy' }

export default async function Policy({ params }: { params: Promise<{ slug: string; id: string }> }) {
  const { slug, id } = await params
  const { supabase, org, role } = await loadState(slug)
  const { data: p } = await supabase.from('policies').select('*').eq('id', id).eq('org_id', org.id).maybeSingle()
  if (!p) notFound()
  const doc = p.body as PolicyDoc
  const approved = p.status === 'approved'
  const markdown = policyToMarkdown(doc, { org: org.name, version: p.version, status: p.status, approvedBy: approved ? p.approved_by_email : null, approvedAt: p.approved_at })
  return (
    <div className="mx-auto max-w-4xl">
      <div className="no-print mb-4 flex flex-wrap items-center justify-between gap-2">
        <Link href={`/o/${slug}/policies`} className="inline-flex items-center gap-1.5 text-sm text-soft hover:text-ink"><ArrowLeft className="size-4" /> Policies</Link>
        <div className="flex flex-wrap gap-2">
          <SaveMarkdown name={`${org.slug}-${p.template_id}-v${p.version}.md`} text={markdown} />
          <PrintButton />
          {p.status === 'draft' && atLeast(role, 'admin') && <ApproveButton slug={slug} id={p.id} />}
        </div>
      </div>
      <article className="card print-plain p-6 lg:p-8">
        <header className="border-b border-line pb-4">
          <p className="eyebrow">{org.name}, version {p.version}, {p.status}</p>
          <h1 className="mt-1 text-3xl">{doc.title}</h1>
          {p.status === 'approved' && <p className="mt-2 text-sm text-soft">Approved by {p.approved_by_email} on {day(p.approved_at)}. Review due {day(p.review_due)}. Text hash <code className="font-mono text-xs">{shortHash(p.content_sha256)}</code>.</p>}
        </header>
        <section className="mt-5"><h2 className="text-lg">Purpose</h2><p className="mt-1 text-soft">{doc.purpose}</p></section>
        <section className="mt-5"><h2 className="text-lg">Scope</h2><p className="mt-1 text-soft">{doc.scope}</p></section>
        {doc.sections.map((s) => (
          <section key={s.heading} className="mt-6">
            <h2 className="text-lg">{s.heading}</h2>
            {s.body && <p className="mt-1 text-soft">{s.body}</p>}
            <div tabIndex={0} role="region" aria-label={s.heading} className="mt-3 overflow-x-auto">
              <table className="w-full min-w-[42rem] text-left text-sm">
                <thead className="text-xs text-faint">
                  <tr className="border-b border-line">{['Commitment', 'Measure', 'Target', 'Owner', 'Within'].map((h) => <th key={h} className="py-2 pr-3 font-medium">{h}</th>)}</tr>
                </thead>
                <tbody>
                  {s.clauses.map((c, i) => (
                    <tr key={i} className="border-b border-line align-top last:border-0">
                      <td className="py-2.5 pr-3"><div className="font-medium">{c.statement}</div><div className="mt-0.5 text-xs text-faint">{c.relevance}</div></td>
                      <td className="py-2.5 pr-3 text-soft">{c.metric}</td>
                      <td className="py-2.5 pr-3 text-soft">{c.target}</td>
                      <td className="py-2.5 pr-3 text-soft">{c.ownerRole}</td>
                      <td className="whitespace-nowrap py-2.5 text-soft">{c.dueDays} days</td>
                    </tr>
                  ))}
                </tbody>
              </table>
            </div>
          </section>
        ))}
        <p className="mt-6 border-t border-line pt-3 text-xs text-faint">Review every {doc.reviewMonths} months. Draft generated by maas.AI GRC Hub for human review, not legal advice.</p>
      </article>
    </div>
  )
}
